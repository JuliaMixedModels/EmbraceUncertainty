const _sizespeed = Ref{Any}(nothing)

"""
    dataset(name::Union{Symbol,AbstractString})

Return the dataset named `name`.

Nearly all of the datasets used in this book are provided by
[MixedModelsDatasets.jl](https://github.com/JuliaMixedModels/MixedModelsDatasets.jl),
which downloads them on first use and caches them in a scratchspace.  Names are
case-insensitive there, so both `:ELP_ldt_trial` and `:elp_ldt_trial` work.

The sole exception is `sizespeed`, which summarizes fits of models that are far
too expensive to reproduce while rendering the book.  It is small enough to be
distributed with this package as `src/sizespeed.csv`, and is regenerated by
`scripts/movielens_sizespeed.jl`.
"""
function dataset(nm::AbstractString)
    lowercase(nm) == "sizespeed" || return MixedModelsDatasets.dataset(nm)
    if isnothing(_sizespeed[])
        # the leading `#` lines record the julia, MixedModels, BLAS and
        # optimizer settings that the table was generated with
        _sizespeed[] = CSV.read(
            joinpath(@__DIR__, "sizespeed.csv"),
            Table;
            comment="#",
            downcast=true,
            pool=false,
        )
    end
    return _sizespeed[]
end

dataset(nm::Symbol) = dataset(string(nm))
